import { randomBytes } from 'node:crypto';
import { degrees, PDFDocument, rgb, StandardFonts } from 'pdf-lib';
import { config } from '../config.js';
import { HttpError } from '../lib/errors.js';

/**
 * e-Stamping (India): stamp duty paid electronically through SHCIL or an
 * authorised vendor, evidenced by an e-stamp certificate attached as the first
 * page of the agreement. Real vendors (SHCIL, or aggregators such as
 * Leegality, Digio and SignDesk) plug in behind StampProvider; their APIs are
 * contract-gated, so only the sandbox ships here.
 */

export const INDIAN_STATES: Record<string, string> = {
  AP: 'Andhra Pradesh',
  BR: 'Bihar',
  DL: 'Delhi',
  GJ: 'Gujarat',
  HR: 'Haryana',
  KA: 'Karnataka',
  KL: 'Kerala',
  MH: 'Maharashtra',
  MP: 'Madhya Pradesh',
  OD: 'Odisha',
  PB: 'Punjab',
  RJ: 'Rajasthan',
  TN: 'Tamil Nadu',
  TS: 'Telangana',
  UP: 'Uttar Pradesh',
  WB: 'West Bengal',
};

export interface EstampRequest {
  state: string;
  /** Article of the state's Stamp Act schedule, e.g. "Article 5(h)" */
  article: string;
  dutyAmount: number;
  firstParty: string;
  secondParty: string;
  purpose: string;
}

export interface EstampResult {
  provider: string;
  certificateNumber: string;
  issuedAt: string;
  state: string;
  article: string;
  dutyAmount: number;
  sandbox: boolean;
}

interface StampProvider {
  id: string;
  purchase(req: EstampRequest, reference: string): Promise<{ result: EstampResult; certificatePdf: Buffer }>;
}

const sandboxProvider: StampProvider = {
  id: 'sandbox',
  async purchase(req, reference) {
    const certificateNumber = `IN-${req.state}${randomBytes(5).toString('hex').toUpperCase()}-SBX`;
    const issuedAt = new Date();
    const doc = await PDFDocument.create();
    const page = doc.addPage([595.28, 841.89]);
    const font = await doc.embedFont(StandardFonts.Helvetica);
    const bold = await doc.embedFont(StandardFonts.HelveticaBold);
    const { width, height } = page.getSize();
    page.drawRectangle({ x: 30, y: 30, width: width - 60, height: height - 60, borderColor: rgb(0.2, 0.45, 0.3), borderWidth: 3 });
    page.drawRectangle({ x: 38, y: 38, width: width - 76, height: height - 76, borderColor: rgb(0.2, 0.45, 0.3), borderWidth: 0.8 });
    page.drawText('SPECIMEN - SANDBOX - NOT A VALID E-STAMP', { x: 75, y: height / 2 - 120, size: 26, font: bold, color: rgb(0.85, 0.2, 0.2), opacity: 0.25, rotate: degrees(35) });
    page.drawText('INDIA NON JUDICIAL', { x: 60, y: height - 90, size: 18, font: bold, color: rgb(0.15, 0.35, 0.25) });
    page.drawText(`Government of ${INDIAN_STATES[req.state] ?? req.state}`, { x: 60, y: height - 112, size: 12, font, color: rgb(0.2, 0.2, 0.2) });
    page.drawText('e-Stamp', { x: width - 140, y: height - 90, size: 18, font: bold, color: rgb(0.15, 0.35, 0.25) });
    const rows: [string, string][] = [
      ['Certificate No.', certificateNumber],
      ['Certificate Issued Date', issuedAt.toISOString().replace('T', ' ').slice(0, 19)],
      ['Unique Doc. Reference', reference],
      ['Purchased by', req.firstParty],
      ['Description of Document', req.article],
      ['Description', req.purpose],
      ['Consideration Price (Rs.)', '0'],
      ['First Party', req.firstParty],
      ['Second Party', req.secondParty],
      ['Stamp Duty Paid By', req.firstParty],
      ['Stamp Duty Amount (Rs.)', `${req.dutyAmount.toFixed(2)}`],
    ];
    let y = height - 170;
    for (const [k, v] of rows) {
      page.drawText(k, { x: 60, y, size: 10, font, color: rgb(0.35, 0.35, 0.35) });
      page.drawText(v.replace(/[^\x20-\x7E]/g, '?').slice(0, 70), { x: 240, y, size: 10, font: bold, color: rgb(0.1, 0.1, 0.1) });
      y -= 22;
    }
    page.drawText('This page was generated by the Nuronix eSign e-stamp sandbox for testing.', { x: 60, y: 80, size: 9, font, color: rgb(0.6, 0.1, 0.1) });
    page.drawText('It is not a stamp paper and has no legal effect.', { x: 60, y: 66, size: 9, font, color: rgb(0.6, 0.1, 0.1) });
    return {
      result: {
        provider: 'sandbox',
        certificateNumber,
        issuedAt: issuedAt.toISOString(),
        state: req.state,
        article: req.article,
        dutyAmount: req.dutyAmount,
        sandbox: true,
      },
      certificatePdf: Buffer.from(await doc.save()),
    };
  },
};

const PROVIDERS: Record<string, StampProvider> = { sandbox: sandboxProvider };

export async function purchaseEstamp(req: EstampRequest, reference: string) {
  const provider = PROVIDERS[config.estamp.provider];
  if (!provider) throw new HttpError(503, 'e-Stamping is not configured.', 'estamp_unavailable');
  return provider.purchase(req, reference);
}

/** Inserts the e-stamp certificate as page 1 of the document. */
export async function prependCertificate(documentPdf: Buffer, certificatePdf: Buffer): Promise<Buffer> {
  const doc = await PDFDocument.load(documentPdf);
  const cert = await PDFDocument.load(certificatePdf);
  const [page] = await doc.copyPages(cert, [0]);
  doc.insertPage(0, page);
  return Buffer.from(await doc.save({ useObjectStreams: false }));
}
